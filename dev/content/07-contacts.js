/* ============================================================================
 * CONTENT · 07-contacts.js
 * 【人脉登记表】这一局里能反复出场的那些"人"。
 *
 * 为什么要单独登记：
 *   一个事件里写「你去找他」很容易，难的是让同一个"他"在十年后再次出现、
 *   并且记得上次你欠了他什么。人脉表解决的就是这件事 ——
 *   事件的成本、门槛、后果都可以挂在某个具体的人身上。
 *
 * 用法（全部在事件里写，引擎自动接管）：
 *   req:     { contact: "fixer" }              认识他，这个选项才可选
 *   contacts:["fixer"]                         事件级门槛：不认识就不会被抽到
 *   effects: { contact: { fixer: 12 } }        好感 +12（第一次出现就代表"从此认识"）
 *   effects: { forget: ["fixer"] }             彻底断掉（你把他卖了，或者他死了）
 *
 * 好感的含义（和派系好感一样，-100 ~ 100）：
 *   30+  可以开口求一件难事      10~29  平时能办事
 *   0~9  只是点头之交            -1~-19 需要先修关系
 *   -20 以下  他会主动坏你的事
 *
 * 设计约定：
 *   1) 一个人只负责一类资源。找钱的别来找他要选票，要选票的别来找他借钱。
 *   2) 人物不写死年代 —— 他们的"位置"在任何年代都存在（1960 年的电视制作人
 *      与 2008 年的电视制作人是同一个人设）。需要限定年代时写在事件上，不写在这里。
 *   3) 新增人物：加一条即可，引擎自动接纳。已写过的事件不受影响。
 * ==========================================================================*/
